#!/usr/bin/env bash
# Заводит задачу: собирает вводные в один файл и печатает команду запуска сессии.
#
# Зачем. По журналам 66 сессий: старт сессии — 62 тыс. токенов контекста,
# медиана по ходам — 394 тыс., девятый дециль — 816 тыс. Одна сессия тянет
# в среднем 18,5 ходов на задачу и живёт неделями, накапливая контекст.
# 62% ходов идут при контексте выше 300 тыс. и дают 84% всего расхода.
# Поэтому: одна задача — одна сессия, вводные собраны заранее файлом.
#
#   task.sh back  <PROJ-123> [заголовок]   — задача на бэк
#   task.sh front <PROJ-123> [заголовок]   — задача на вёрстку
#   task.sh review <адрес запроса>              — ревью запроса на слияние
#
# Складывает в .tasks/<ключ>/brief.md и печатает готовую команду.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
TASKS=${ORCH_TASKS_DIR:-$ROOT/.tasks}

KIND=${1:?back | front | review}
ARG=${2:?ключ задачи или адрес запроса}
TITLE=${3:-}

slug() { echo "$1" | tr '[:upper:]' '[:lower:]' | tr -cs 'a-z0-9' '-' | sed 's/^-//;s/-$//'; }

case "$KIND" in
  back|front)
    KEY=$ARG
    DIR="$TASKS/$(slug "$KEY")"
    mkdir -p "$DIR"
    BRIEF="$DIR/brief.md"
    # Заполненную вводную не затирать: в ней цель, «Самопроверка» и ход работы.
    if [ -f "$BRIEF" ]; then
      echo "вводная: $BRIEF (уже есть, не перезаписана)"
      echo
      echo "запускать отдельной сессией, из корня workspace:"
      echo "  claude \"Задача $KEY. Вводная: $BRIEF. Начни с неё.\""
      exit 0
    fi
    {
      echo "# $KEY${TITLE:+ — $TITLE}"
      echo
      echo "- вид: $([ "$KIND" = back ] && echo 'бэк' || echo 'вёрстка')"
      echo "- заведено: $(date +%F)"
      [ -n "${ORCH_TRACKER_URL:-}" ] && echo "- задача: ${ORCH_TRACKER_URL%/}/$KEY"
      echo
      echo "## Что сделать"
      echo
      echo "_(заполняется в начале сессии: цель одной фразой и критерий готовности)_"
      echo
      echo "## Границы"
      echo
      echo "- трогаем:"
      echo "- не трогаем:"
      echo "- куда сливать: _(не та ветка, от которой нарезались, а та, куда в этом"
      echo "  репозитории реально сливают задачи — см. шаг 4)_"
      echo
      echo "## Чем проверяем"
      echo
      if [ "$KIND" = back ]; then
        cat <<'EOT'
- локальный прогон тестов по затронутому пути (скилл `local-test-runs`)
- после открытия запроса — `scripts/orch/mr-brief.py <адрес> --out review.md`
  и ревью по выжимке, а не по полному диффу
EOT
      else
        cat <<'EOT'
- визуальная сверка экрана с эталонами, если для проекта она настроена; расхождение выше
  допуска разбирать по вырезке, полный кадр в сессию не тянуть
- юнит-тесты и проверка типов по затронутому пакету
EOT
      fi
      echo
      echo "## Самопроверка"
      echo
      echo "_(заполняется перед сдачей: по строке на каждый скилл — $("$ROOT/scripts/orch/selfcheck.py" --skills "$KIND") —"
      echo "его пункты «Самопроверки» → ответ с доказательством либо «не применимо, потому что …»)_"
      echo
      echo "## Порядок работы"
      echo
      cat <<'EOT'
1. Прочитать эту вводную и дописать цель с критерием готовности.
2. Поиск по коду — через подагента (`Explore`), в главную сессию тянуть выводы,
   а не выдачу поиска.
3. Если сценарий делает больше одной записи — таблица шагов и повторов
   (retry-safe-writes §1) до правки.
4. Правки и прогон проверок; фикстуры — с прод-формы данных.
5. Самопроверка по чек-листам скиллов классов дефектов — раздел выше.
6. Цель слияния определить ДО открытия запроса, а не по ветке-основанию:
   посмотреть, куда ушли последние слитые запросы (`state=merged`, поле
   `target_branch`). Задачная ветка идёт в релизную линию либо в промежуточную;
   прямо в защищённую ветку продакшена её не заводят — туда сливают только
   релизные и сборочные ветки. Номер релизной ветки читать
   не по названию, а по предкам: линия с большим номером бывает уже впитанной
   и лежащей позади (`git merge-base --is-ancestor`).
7. Запрос на слияние. Целей несколько — по запросу на каждую, коммит переносить
   `cherry-pick`, а не сливать ветку целиком: она притащит в релиз чужие merge-записи.
8. Ревью по выжимке.
EOT
    } > "$BRIEF"
    echo "вводная: $BRIEF"
    echo
    echo "запускать отдельной сессией, из корня workspace:"
    echo "  claude \"Задача $KEY. Вводная: $BRIEF. Начни с неё.\""
    ;;

  review)
    URL=$ARG
    KEY=$(echo "$URL" | sed -E 's#.*/([^/]+)/-/merge_requests/([0-9]+).*#\1-\2#')
    DIR="$TASKS/review-$(slug "$KEY")"
    mkdir -p "$DIR"
    echo "собираю выжимку запроса…"
    "$ROOT/scripts/orch/mr-brief.py" "$URL" --out "$DIR/brief.md"
    echo
    echo "запускать отдельной сессией:"
    echo "  claude \"Ревью запроса. Выжимка: $DIR/brief.md — читай её вместо полного диффа. Скилл review-delegation.\""
    ;;

  *) echo "вид должен быть back, front или review" >&2; exit 1 ;;
esac
